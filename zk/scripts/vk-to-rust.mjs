// Converts a snarkjs Groth16 verification_key.json into the byte layout expected by
// `groth16-solana` (alt_bn128 syscalls, EIP-197 big-endian encoding):
//   G1 = x || y                       (32 bytes each, big-endian)
//   G2 = x.c1 || x.c0 || y.c1 || y.c0 (imaginary part first)
import { readFileSync, writeFileSync } from "node:fs";

const [, , vkPath, outPath] = process.argv;
if (!vkPath || !outPath) {
  console.error("usage: node vk-to-rust.mjs <verification_key.json> <out.rs>");
  process.exit(1);
}
const vk = JSON.parse(readFileSync(vkPath, "utf8"));

const be32 = (dec) => {
  const hex = BigInt(dec).toString(16).padStart(64, "0");
  return Array.from(Buffer.from(hex, "hex"));
};
const g1 = (p) => [...be32(p[0]), ...be32(p[1])];
const g2 = (p) => [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])];
const arr = (bytes) => `[${bytes.join(", ")}]`;

const rs = `// @generated by zk/scripts/vk-to-rust.mjs from zk/build/verification_key.json — do not edit.
// Circuit: zk/circuits/repayment_certificate.circom (protocol: ${vk.protocol}, curve: ${vk.curve})
use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},
    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},
    vk_gamme_g2: ${arr(g2(vk.vk_gamma_2))},
    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},
    vk_ic: &[
${vk.IC.map((p) => `        ${arr(g1(p))},`).join("\n")}
    ],
};
`;
writeFileSync(outPath, rs);
console.log(`wrote ${outPath} (${vk.nPublic} public inputs)`);
