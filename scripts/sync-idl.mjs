// Copies the Anchor-generated IDL + types into the shared SDK as a plain TS module
// (avoids JSON-import differences between Node, tsx and Next.js).
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("..", import.meta.url).pathname;
const idl = readFileSync(`${root}target/idl/loom.json`, "utf8");
const types = readFileSync(`${root}target/types/loom.ts`, "utf8");
writeFileSync(`${root}sdk/src/idl/loom.ts`, types);
writeFileSync(
  `${root}sdk/src/idl/index.ts`,
  `// @generated by scripts/sync-idl.mjs — do not edit.\nimport type { Loom } from "./loom";\nexport type { Loom };\nexport const IDL: Loom = ${idl.trim()} as unknown as Loom;\n`,
);
console.log("synced IDL into sdk/src/idl");
